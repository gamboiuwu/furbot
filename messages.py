"""Pools of human-sounding message variants for the verification DMs.

The bot picks a random line each time so it doesn't read like a robot saying
the same thing over and over. Tone: casual and natural, mostly emote-free, with
the occasional kaomoji (^_^, owo, ^w^, :3, >w<) sprinkled in.

Placeholders use {tokens}: {server}, {role}, {chan}, {hours}.
"""

from __future__ import annotations

import random


def _render(template: str, **kw) -> str:
    for key, value in kw.items():
        template = template.replace("{" + key + "}", str(value))
    return template


def pick(pool: list[str], **kw) -> str:
    return _render(random.choice(pool), **kw)


